import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:intl/intl.dart';
import '../models/settings_model.dart';
import 'pdf_header_helper.dart';

class PdfReportHelper {
  static Future<List<int>> generateReport({
    required AppSettings settings,
    required String title,
    required List<String> columns,
    required List<List<String>> data,
    required Map<String, double> summaries,
  }) async {
    final pdf = pw.Document();

    // Add Page
    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) {
          return [
            // Header
            PdfHeaderHelper.buildHeader(
              settings: settings, 
              title: title, 
              showDate: true
            ),
            pw.SizedBox(height: 20),

            // Summary Section
            if (summaries.isNotEmpty)
              pw.Container(
                padding: const pw.EdgeInsets.all(10),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: PdfColors.grey300),
                  borderRadius: pw.BorderRadius.circular(4),
                ),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
                  children: summaries.entries.map((e) {
                    return pw.Column(
                      children: [
                        pw.Text(e.key, style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
                        pw.Text('INR ${e.value.toStringAsFixed(2)}', style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)),
                      ],
                    );
                  }).toList(),
                ),
              ),
              
            pw.SizedBox(height: 20),

            // Table
            pw.Table.fromTextArray(
              headers: columns,
              data: data,
              border: pw.TableBorder.all(color: PdfColors.grey300),
              headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
              headerDecoration: const pw.BoxDecoration(color: PdfColors.grey100),
              cellAlignment: pw.Alignment.centerLeft,
              cellPadding: const pw.EdgeInsets.all(5),
            ),
            
            pw.SizedBox(height: 20),
            pw.Divider(),
            pw.Align(
              alignment: pw.Alignment.centerRight,
              child: pw.Text('Generated by DigiInvi', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey)),
            ),
          ];
        },
      ),
    );

    return pdf.save();
  }
}
