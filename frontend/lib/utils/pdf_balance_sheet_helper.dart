import 'package:flutter/services.dart';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/balance_sheet_model.dart';
import '../models/settings_model.dart';
import 'pdf_header_helper.dart';
import 'file_download_helper.dart';

class PdfBalanceSheetHelper {
  Future<void> generateAndDownload(BalanceSheetData data, AppSettings settings) async {
    final bytes = await generateBytes(data, settings);
    await FileDownloadHelper.downloadFile(
      bytes, 
      'balance_sheet_${DateFormat('yyyyMMdd').format(data.asOnDate)}', 
      'pdf'
    );
  }

  Future<Uint8List> generateBytes(BalanceSheetData data, AppSettings settings) async {
    final pdf = pw.Document();
    
    // Load Fonts or Logo if needed (Basic layout for now)
    
    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) {
          return [
            PdfHeaderHelper.buildHeader(
              settings: settings, 
              title: 'Balance Sheet', 
              subtitle: 'Data as on ${DateFormat('dd MMM yyyy').format(data.asOnDate)}',
              date: data.asOnDate
            ),
            pw.SizedBox(height: 20),
            _buildSectionTitle('Assets'),
            _buildRow('Cash & Bank Balance', data.cashAndBank),
            _buildRow('Accounts Receivable', data.accountsReceivable),
            _buildTotalRow('Total Assets', data.totalAssets),
            pw.SizedBox(height: 20),
            _buildSectionTitle('Liabilities'),
            _buildRow('GST Payable', data.gstPayable),
            _buildTotalRow('Total Liabilities', data.totalLiabilities),
            pw.SizedBox(height: 20),
            _buildSectionTitle('Equity'),
            _buildRow('Net Profit (Retained Earnings)', data.netProfit),
            _buildTotalRow('Total Equity', data.totalEquity),
            pw.SizedBox(height: 30),
            pw.Divider(),
            _buildFooter(),
          ];
        },
      ),
    );

    return pdf.save();
  }

  pw.Widget _buildSectionTitle(String title) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 8),
      child: pw.Text(title, style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: PdfColors.blue800)),
    );
  }

  pw.Widget _buildRow(String label, double value) {
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(vertical: 4),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(label),
          pw.Text(_formatCurrency(value)),
        ],
      ),
    );
  }

  pw.Widget _buildTotalRow(String label, double value) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(top: 8),
      padding: const pw.EdgeInsets.only(top: 8),
      decoration: const pw.BoxDecoration(
        border: pw.Border(top: pw.BorderSide(width: 1)),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(label, style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
          pw.Text(_formatCurrency(value), style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        ],
      ),
    );
  }

  pw.Widget _buildFooter() {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          "Disclaimer: This balance sheet is system-generated based on the data entered in DigiInvi. It is intended for business analysis and reference purposes only. For statutory compliance, tax filing, or bank submission, verification by a qualified Chartered Accountant (CA) is recommended.",
          textAlign: pw.TextAlign.justify,
          style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
        ),
        pw.SizedBox(height: 10),
        pw.Align(
          alignment: pw.Alignment.centerRight,
          child: pw.Text('Generated by DigiInvi', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey400)),
        ),
      ],
    );
  }

  String _formatCurrency(double amount) {
    return NumberFormat.currency(symbol: 'INR ', decimalDigits: 2, locale: 'en_IN').format(amount);
  }
}
